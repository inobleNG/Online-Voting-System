import React, { useState } from 'react';
import { ShieldAlert, KeyRound, ArrowRight } from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import { Modal } from '../common/Modal';

export const TwoFactorModal: React.FC = () => {
  const { twoFactorRequired, verify2FACode } = useAuth();
  const [code, setCode] = useState('');
  const [error, setError] = useState<string | null>(null);

  if (!twoFactorRequired) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (code.length < 6) {
      setError('Please enter a valid 6-digit security code');
      return;
    }
    const ok = verify2FACode(code);
    if (!ok) {
      setError('Invalid 2FA Verification code. Try code: 123456');
    }
  };

  return (
    <Modal
      isOpen={twoFactorRequired}
      onClose={() => {}}
      title="National Security Two-Factor Verification"
      subtitle="High-security sovereign election protocol requires second-tier accreditation"
      maxWidth="sm"
      icon={<ShieldAlert className="h-5 w-5 text-[#008751]" />}
    >
      <form onSubmit={handleSubmit} className="space-y-4 py-2 text-[#0F291E]">
        <div className="rounded-lg border border-slate-200 bg-slate-50 p-3 text-xs text-slate-700">
          Enter the 6-digit TOTP token generated by your secure token app (Demo fallback: <strong className="font-mono text-slate-900">123456</strong>).
        </div>

        {error && (
          <div className="rounded-lg border border-rose-200 bg-rose-50 p-2.5 text-xs text-rose-700 font-medium">
            {error}
          </div>
        )}

        <div>
          <label className="block text-xs font-medium text-slate-700 mb-1.5 text-center">
            6-Digit Verification Token
          </label>
          <input
            type="text"
            maxLength={6}
            value={code}
            onChange={(e) => {
              setCode(e.target.value.replace(/\D/g, ''));
              setError(null);
            }}
            placeholder="123456"
            className="w-full text-center font-mono text-2xl tracking-[0.4em] py-2.5 rounded-lg border border-slate-200 bg-white text-[#008751] font-bold focus:border-[#008751] focus:outline-none transition-colors"
            autoFocus
          />
        </div>

        <button
          type="submit"
          className="flex w-full items-center justify-center gap-2 rounded-lg bg-[#008751] hover:bg-[#007043] py-2.5 text-xs font-semibold text-white transition-colors cursor-pointer"
        >
          <KeyRound className="h-4 w-4" />
          <span>Verify &amp; Access System</span>
          <ArrowRight className="h-4 w-4" />
        </button>
      </form>
    </Modal>
  );
};

